const plural = (n: number, one: string, many: string): string => `${n} ${n === 1 ? one : many}`
/** Romanian counts: one, a few (0, and ending in 1–19), many, with "de" from 20 on. */
const romanian = (n: number, one: string, few: string): string => {
  const tail = n % 100
  if (n === 1) return `1 ${one}`
  return n === 0 || (tail >= 1 && tail <= 19) ? `${n} ${few}` : `${n} de ${few}`
}

