const plural = (n: number, one: string, many: string): string => `${n} ${n === 1 ? one : many}`
/** Czech counts: one, a few (2–4), many. */
const czech = (n: number, one: string, few: string, many: string): string => `${n} ${n === 1 ? one : n >= 2 && n <= 4 ? few : many}`
/** Polish counts: one, a few (ending in 2–4, not 12–14), many. */
const polish = (n: number, one: string, few: string, many: string): string => {
  const units = n % 10
  const tens = n % 100
  return `${n} ${n === 1 ? one : units >= 2 && units <= 4 && (tens < 12 || tens > 14) ? few : many}`
}

