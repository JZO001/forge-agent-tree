/** Slovak counts: one, a few (2–4), many. */
const slovak = (n: number, one: string, few: string, many: string): string => `${n} ${n === 1 ? one : n >= 2 && n <= 4 ? few : many}`
/** Slovenian counts by the last two digits: one (1), two (2), a few (3–4), many. */
const slovenian = (n: number, one: string, two: string, few: string, many: string): string => {
  const tail = n % 100
  return `${n} ${tail === 1 ? one : tail === 2 ? two : tail === 3 || tail === 4 ? few : many}`
}
/** Serbian counts: one (ending in 1, not 11), else the other form. */
const serbian = (n: number, one: string, other: string): string => `${n} ${n % 10 === 1 && n % 100 !== 11 ? one : other}`

